#!/usr/bin/env node
'use strict';

/**
 * opencode-context-compressor CLI Installer
 *
 * Commands:
 *   node bin/cli.js install   — Full install: CA cert, system trust, wrapper script, systemd service
 *   node bin/cli.js uninstall — Remove wrapper script and systemd service
 *   node bin/cli.js status    — Show proxy status and memory stats
 */

const fs = require('fs');
const path = require('path');
const os = require('os');
const { execSync, spawnSync } = require('child_process');

const HOME = os.homedir();
const PROJECT_DIR = path.resolve(__dirname, '..');
const DAEMON_SCRIPT = path.join(PROJECT_DIR, 'src', 'daemon.js');
const MCP_SERVER_SCRIPT = path.join(PROJECT_DIR, 'src', 'mcp-server.js');
const NODE_BIN = process.execPath;

const OPENCODE_CONFIG = path.join(HOME, '.config', 'opencode', 'opencode.json');
const SYSTEMD_DIR = path.join(HOME, '.config', 'systemd', 'user');
const SERVICE_FILE = path.join(SYSTEMD_DIR, 'context-compressor.service');

const CA_DIR = path.join(HOME, '.context-compressor', 'ca');
const CA_CERT_PATH = path.join(CA_DIR, 'ca.crt');

// ─── Wrapper script ──────────────────────────────────────────────────────────

function findOpencode() {
  try {
    return execSync('which opencode', { encoding: 'utf8' }).trim();
  } catch (_) {
    return 'opencode'; // fallback to PATH
  }
}

function installWrapper() {
  const opencodeBin = findOpencode();
  const wrapperContent = `#!/bin/bash
# opencode-cc — OpenCode launcher with context-compressor MITM proxy
# Generated by opencode-context-compressor installer

export HTTP_PROXY=http://127.0.0.1:3266
export HTTPS_PROXY=http://127.0.0.1:3266
export http_proxy=http://127.0.0.1:3266
export https_proxy=http://127.0.0.1:3266
export NODE_EXTRA_CA_CERTS="${CA_CERT_PATH}"
exec "${opencodeBin}" "$@"
`;

  // Try to write to /usr/local/bin (needs sudo), fallback to ~/.local/bin
  const targets = ['/usr/local/bin/opencode-cc', path.join(HOME, '.local', 'bin', 'opencode-cc')];
  for (const target of targets) {
    try {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, wrapperContent, { mode: 0o755 });
      console.log(`✅ Wrapper script installed: ${target}`);
      console.log(`   Run OpenCode via: opencode-cc`);
      return target;
    } catch (_) {
      // Try next target
    }
  }
  console.log(`⚠️  Could not install wrapper to /usr/local/bin. Add this to your shell profile:`);
  console.log(`   alias opencode-cc='HTTP_PROXY=http://127.0.0.1:3266 HTTPS_PROXY=http://127.0.0.1:3266 NODE_EXTRA_CA_CERTS="${CA_CERT_PATH}" opencode'`);
}

// ─── CA trust installation ───────────────────────────────────────────────────

function installCATrust() {
  if (!fs.existsSync(CA_CERT_PATH)) {
    console.log('🔐 Root CA not yet generated — starting proxy to generate it...');
    // Spawn proxy briefly just to generate the cert
    const result = spawnSync(NODE_BIN, ['-e', `require('${path.join(PROJECT_DIR, 'src', 'ca.js')}').getCA(); setTimeout(()=>process.exit(0),500);`], { timeout: 10000 });
    if (!fs.existsSync(CA_CERT_PATH)) {
      console.log('⚠️  CA cert generation failed. Proxy will generate it on first start.');
      return;
    }
  }

  console.log(`🔐 Root CA certificate: ${CA_CERT_PATH}`);

  // Try to install system-wide (Linux: update-ca-certificates / Arch: trust)
  const methods = [
    // Ubuntu/Debian
    () => {
      const dest = '/usr/local/share/ca-certificates/context-compressor-ca.crt';
      execSync(`sudo cp "${CA_CERT_PATH}" "${dest}" && sudo update-ca-certificates`, { stdio: 'pipe' });
      console.log('✅ CA installed into system trust store (update-ca-certificates)');
    },
    // Fedora/RHEL
    () => {
      const dest = '/etc/pki/ca-trust/source/anchors/context-compressor-ca.crt';
      execSync(`sudo cp "${CA_CERT_PATH}" "${dest}" && sudo update-ca-trust`, { stdio: 'pipe' });
      console.log('✅ CA installed into system trust store (update-ca-trust)');
    },
    // Arch Linux
    () => {
      const dest = '/etc/ca-certificates/trust-source/anchors/context-compressor-ca.crt';
      execSync(`sudo cp "${CA_CERT_PATH}" "${dest}" && sudo trust extract-compat`, { stdio: 'pipe' });
      console.log('✅ CA installed into system trust store (trust extract-compat)');
    },
  ];

  let installed = false;
  for (const method of methods) {
    try {
      method();
      installed = true;
      break;
    } catch (_) { /* try next */ }
  }

  // Chrome/Chromium NSS (no sudo needed)
  try {
    const nssDirs = [
      path.join(HOME, '.pki', 'nssdb'),
      path.join(HOME, 'snap', 'chromium', 'current', '.pki', 'nssdb'),
    ].filter(fs.existsSync);
    for (const nssDir of nssDirs) {
      execSync(`certutil -A -n "context-compressor-ca" -t "CT,," -i "${CA_CERT_PATH}" -d "sql:${nssDir}"`, { stdio: 'pipe' });
      console.log(`✅ CA installed into Chrome NSS database: ${nssDir}`);
    }
  } catch (_) { /* certutil not available */ }

  if (!installed) {
    console.log(`⚠️  Could not auto-install CA into system trust. Add manually:`);
    console.log(`   sudo cp "${CA_CERT_PATH}" /usr/local/share/ca-certificates/context-compressor-ca.crt`);
    console.log(`   sudo update-ca-certificates`);
  }
}

// ─── Systemd service ──────────────────────────────────────────────────────────

function installSystemd() {
  fs.mkdirSync(SYSTEMD_DIR, { recursive: true });
  const service = `[Unit]
Description=OpenCode Context Compressor MITM Proxy & ModelMemo MCP
After=network.target

[Service]
Type=simple
WorkingDirectory=${PROJECT_DIR}
ExecStart=${NODE_BIN} ${DAEMON_SCRIPT}
Restart=always
RestartSec=3
Environment=NODE_ENV=production

[Install]
WantedBy=default.target
`;
  fs.writeFileSync(SERVICE_FILE, service);
  try {
    execSync('systemctl --user daemon-reload', { stdio: 'ignore' });
    execSync('systemctl --user enable context-compressor.service', { stdio: 'ignore' });
    execSync('systemctl --user restart context-compressor.service', { stdio: 'ignore' });
    console.log('🟢 Systemd service context-compressor.service enabled and running');
  } catch (err) {
    console.log(`⚠️  Systemd: ${err.message}`);
  }
}

// ─── MCP registration ────────────────────────────────────────────────────────

function installMCP() {
  fs.mkdirSync(path.dirname(OPENCODE_CONFIG), { recursive: true });
  let config = {};
  if (fs.existsSync(OPENCODE_CONFIG)) {
    try { config = JSON.parse(fs.readFileSync(OPENCODE_CONFIG, 'utf8')); } catch (_) {}
  }
  if (!config.mcp || typeof config.mcp !== 'object') config.mcp = {};
  config.mcp['model-memo'] = {
    type: 'local',
    command: [NODE_BIN, MCP_SERVER_SCRIPT],
    enabled: true,
  };
  // Remove legacy plugin entry (no longer needed — proxy handles interception)
  if (Array.isArray(config.plugin)) {
    config.plugin = config.plugin.filter((p) => !p.includes('context-compressor'));
    if (config.plugin.length === 0) delete config.plugin;
  }
  fs.writeFileSync(OPENCODE_CONFIG, JSON.stringify(config, null, 2));
  console.log(`✅ model-memo MCP server registered in ${OPENCODE_CONFIG}`);
}

// ─── Install ─────────────────────────────────────────────────────────────────

function install() {
  console.log('⚡ Installing opencode-context-compressor (MITM Proxy mode)...\n');
  installMCP();
  installCATrust();
  installWrapper();
  installSystemd();
  console.log(`
🎉 Installation complete!

  Start OpenCode through the proxy:
    opencode-cc

  Or manually:
    HTTP_PROXY=http://127.0.0.1:3266 HTTPS_PROXY=http://127.0.0.1:3266 opencode

  In-chat commands:
    $context-compressor status
    $context-compressor on / off
    $context-compressor help
`);
}

// ─── Status ──────────────────────────────────────────────────────────────────

function status() {
  const memoStore = require('../src/memo-store');
  const stats = memoStore.stats();
  console.log('⚡ opencode-context-compressor Status');
  console.log(`- Proxy: http://127.0.0.1:3266`);
  console.log(`- CA Cert: ${CA_CERT_PATH} (${fs.existsSync(CA_CERT_PATH) ? '✅ exists' : '❌ missing'})`);
  console.log(`- Memory Checkpoints: ${stats.entries} items across ${stats.sessions} session(s)`);
  try {
    const svc = execSync('systemctl --user is-active context-compressor.service', { encoding: 'utf8' }).trim();
    console.log(`- Systemd Service: 🟢 ${svc}`);
  } catch (_) {
    console.log(`- Systemd Service: 🔴 inactive`);
  }
}

// ─── Uninstall ───────────────────────────────────────────────────────────────

function uninstall() {
  try { execSync('systemctl --user stop context-compressor.service', { stdio: 'ignore' }); } catch (_) {}
  try { execSync('systemctl --user disable context-compressor.service', { stdio: 'ignore' }); } catch (_) {}
  if (fs.existsSync(SERVICE_FILE)) fs.unlinkSync(SERVICE_FILE);
  ['/usr/local/bin/opencode-cc', path.join(HOME, '.local', 'bin', 'opencode-cc')].forEach((p) => {
    try { fs.unlinkSync(p); } catch (_) {}
  });
  console.log('✅ opencode-context-compressor uninstalled.');
}

// ─── Main ────────────────────────────────────────────────────────────────────

const arg = (process.argv[2] || 'install').toLowerCase();
if (arg === 'status') status();
else if (arg === 'uninstall') uninstall();
else install();
